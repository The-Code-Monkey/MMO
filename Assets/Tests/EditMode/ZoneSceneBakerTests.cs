    /// <summary>
    /// The issue's ask made literal: two independent zone scenes assembled from the graybox
    /// <em>prefab</em> kit — a safe town and a hostile wilderness — each its own server (distinct
    /// port, distinct zone id) with a portal road to the other and a risk tier the death rules can
    /// read. No ProBuilder anywhere: every piece is a prefab instance.
    ///
    /// The scenes are generated by the baker in <see cref="OneTimeSetUp"/> and removed again in
    /// <see cref="OneTimeTearDown"/> unless they already existed, so the suite exercises the real
    /// produced artifacts without leaving them behind on a clean checkout.
    /// </summary>
    // These tests bake assets and re-import them per test, which costs seconds each; the
    // Unity Tests workflow shards them by category so they run in parallel with the suite.
    [Category("Bake")]
    [Category("BakeContent")]
    public sealed class ZoneSceneBakerTests
    {
        private EditorBuildSettingsScene[] _originalBuildScenes;
        private bool _safeExisted;
        private bool _wildernessExisted;
        private bool _testExisted;

        [OneTimeSetUp]
        public void BuildZones()
        {
            _originalBuildScenes = EditorBuildSettings.scenes;
            _safeExisted = AssetDatabase.LoadAssetAtPath<SceneAsset>(ZoneSceneBaker.SafeZonePath) != null;
            _wildernessExisted = AssetDatabase.LoadAssetAtPath<SceneAsset>(ZoneSceneBaker.WildernessZonePath) != null;
            _testExisted = AssetDatabase.LoadAssetAtPath<SceneAsset>(ZoneSceneBaker.TestZonePath) != null;

            ZoneSceneBaker.BuildBoth();
        }

        [OneTimeTearDown]
        public void RemoveZones()
        {
            EditorBuildSettings.scenes = _originalBuildScenes;

            if (!_safeExisted)
                AssetDatabase.DeleteAsset(ZoneSceneBaker.SafeZonePath);

            if (!_wildernessExisted)
                AssetDatabase.DeleteAsset(ZoneSceneBaker.WildernessZonePath);

            if (!_testExisted)
                AssetDatabase.DeleteAsset(ZoneSceneBaker.TestZonePath);

            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        }

        [SetUp]
        public void ResetActiveScene()
        {
            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        }

