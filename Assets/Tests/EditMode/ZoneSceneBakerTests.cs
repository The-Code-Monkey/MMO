    /// <summary>
    /// The issue's ask made literal: two independent zone scenes assembled from the graybox
    /// <em>prefab</em> kit — a safe town and a hostile wilderness — each its own server (distinct
    /// port, distinct zone id) with a portal road to the other and a risk tier the death rules can
    /// read. No ProBuilder anywhere: every piece is a prefab instance.
    ///
    /// The scenes are generated by the baker in <see cref="OneTimeSetUp"/> and removed again in
    /// <see cref="OneTimeTearDown"/> unless they already existed, so the suite exercises the real
    /// produced artifacts without leaving them behind on a clean checkout.
    /// </summary>
    public sealed class ZoneSceneBakerTests
    {
        private EditorBuildSettingsScene[] _originalBuildScenes;
        private bool _safeExisted;
        private bool _wildernessExisted;

        [OneTimeSetUp]
        public void BuildZones()
        {
            _originalBuildScenes = EditorBuildSettings.scenes;
            _safeExisted = AssetDatabase.LoadAssetAtPath<SceneAsset>(ZoneSceneBaker.SafeZonePath) != null;
            _wildernessExisted = AssetDatabase.LoadAssetAtPath<SceneAsset>(ZoneSceneBaker.WildernessZonePath) != null;

            ZoneSceneBaker.BuildBoth();
        }

        [OneTimeTearDown]
        public void RemoveZones()
        {
            EditorBuildSettings.scenes = _originalBuildScenes;

            if (!_safeExisted)
                AssetDatabase.DeleteAsset(ZoneSceneBaker.SafeZonePath);

            if (!_wildernessExisted)
                AssetDatabase.DeleteAsset(ZoneSceneBaker.WildernessZonePath);

            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        }

        [SetUp]
        public void ResetActiveScene()
        {
            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        }

        // ---- Scenes and their managers ------------------------------------

        [Test]
        public void BothZoneScenes_AreInEnabledBuildSettings()
        {
            string[] enabled = EditorBuildSettings.scenes
                .Where(scene => scene.enabled)
                .Select(scene => scene.path)
                .ToArray();

            CollectionAssert.Contains(enabled, ZoneSceneBaker.SafeZonePath);
            CollectionAssert.Contains(enabled, ZoneSceneBaker.WildernessZonePath);
        }

        [Test]
        public void SafeZone_HasANetworkManager()
        {
            InScene(ZoneSceneBaker.SafeZonePath, scene =>
                Assert.IsTrue(NetworkManagerSceneBaker.Validate(scene, out string error), error));
        }

        [Test]
        public void Wilderness_HasANetworkManager()
        {
            InScene(ZoneSceneBaker.WildernessZonePath, scene =>
                Assert.IsTrue(NetworkManagerSceneBaker.Validate(scene, out string error), error));
        }

        [Test]
        public void BothZoneScenes_HaveAnAuthoredCameraRig()
        {
            InScene(ZoneSceneBaker.SafeZonePath, scene =>
                Assert.IsTrue(LocalCameraBaker.Validate(scene, out string error), error));
            InScene(ZoneSceneBaker.WildernessZonePath, scene =>
                Assert.IsTrue(LocalCameraBaker.Validate(scene, out string error), error));
        }

        // ---- Two servers, not two rooms -----------------------------------

        [Test]
        public void Zones_RunOnDistinctPorts()
        {
            Assert.AreEqual(ZoneSceneBaker.SafeZonePort, PortOf(ZoneSceneBaker.SafeZonePath));
            Assert.AreEqual(ZoneSceneBaker.WildernessZonePort, PortOf(ZoneSceneBaker.WildernessZonePath));
            Assert.AreNotEqual(ZoneSceneBaker.SafeZonePort, ZoneSceneBaker.WildernessZonePort,
                "Two processes on one host need two ports; the whole point is running both locally.");
        }

        [Test]
        public void Zones_DeclareDistinctZoneIds()
        {
            Assert.AreEqual(ZoneSceneBaker.SafeZoneServerId, ZoneIdOf(ZoneSceneBaker.SafeZonePath));
            Assert.AreEqual(ZoneSceneBaker.WildernessServerId, ZoneIdOf(ZoneSceneBaker.WildernessZonePath));
        }

        [Test]
        public void Zones_JoinWithTokenAuth()
        {
            Assert.IsTrue(UseTokenAuthOf(ZoneSceneBaker.SafeZonePath),
                "Cross-zone joins carry the backend session token the gate validates.");
            Assert.IsTrue(UseTokenAuthOf(ZoneSceneBaker.WildernessZonePath));
        }

        // ---- Risk tiers ----------------------------------------------------

        [Test]
        public void SafeZone_DeclaresTheSafeTier()
        {
            Assert.AreEqual(ZoneRiskTier.Safe, RiskTierOf(ZoneSceneBaker.SafeZonePath));
        }

        [Test]
        public void Wilderness_DeclaresTheRedTier()
        {
            Assert.AreEqual(ZoneRiskTier.Red, RiskTierOf(ZoneSceneBaker.WildernessZonePath));
        }

        [Test]
        public void Wilderness_HasRedHazardVolumes()
        {
            InScene(ZoneSceneBaker.WildernessZonePath, scene =>
            {
                Transform hazards = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.HazardsName);
                Assert.IsNotNull(hazards);
                Assert.Greater(hazards.childCount, 0, "A wilderness with no hazard volumes is just a differently coloured town.");

                foreach (Transform hazard in hazards)
                {
                    var config = hazard.GetComponent<ZoneRiskConfig>();
                    Assert.IsNotNull(config, $"'{hazard.name}' must declare a risk tier.");
                    Assert.GreaterOrEqual((int)config.Tier, (int)ZoneRiskTier.Red);
                    Assert.IsNotNull(hazard.GetComponent<Collider>(), "A hazard volume is only hazard-sized if it has bounds.");
                }
            });
        }

        // ---- Portals -------------------------------------------------------

        [Test]
        public void PortalFromSafeZone_PointsAtWilderness()
        {
            PortalFields portal = PortalOf(ZoneSceneBaker.SafeZonePath, "PortalToWilderness");

            Assert.AreEqual(ZoneSceneBaker.DefaultTargetHost, portal.TargetHost);
            Assert.AreEqual(ZoneSceneBaker.WildernessZonePort, portal.TargetPort);
            Assert.AreEqual(ZoneSceneBaker.WildernessServerId, portal.TargetServerId);
            Assert.AreEqual(ZoneSceneBaker.WildernessZoneName, portal.TargetZoneName);
            Assert.AreEqual(ZoneSceneBaker.SafeZoneServerId, portal.SourceServerId);
        }

        [Test]
        public void PortalFromWilderness_PointsAtSafeZone()
        {
            PortalFields portal = PortalOf(ZoneSceneBaker.WildernessZonePath, "PortalToSafeZone");

            Assert.AreEqual(ZoneSceneBaker.DefaultTargetHost, portal.TargetHost);
            Assert.AreEqual(ZoneSceneBaker.SafeZonePort, portal.TargetPort);
            Assert.AreEqual(ZoneSceneBaker.SafeZoneServerId, portal.TargetServerId);
            Assert.AreEqual(ZoneSceneBaker.SafeZoneName, portal.TargetZoneName);
            Assert.AreEqual(ZoneSceneBaker.WildernessServerId, portal.SourceServerId);
        }

        // ---- Geometry is the prefab kit, not ProBuilder --------------------

        [Test]
        public void Ground_IsCoveredByGrayboxFloorPrefabs()
        {
            InScene(ZoneSceneBaker.SafeZonePath, scene =>
            {
                Transform ground = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.GroundName);
                Assert.IsNotNull(ground);

                int tilesPerSide = Mathf.RoundToInt(ZoneSceneBaker.GroundExtent / ZoneSceneBaker.GroundTile);
                Assert.AreEqual(tilesPerSide * tilesPerSide, ground.childCount);

                foreach (Transform tile in ground)
                    AssertIsGrayboxPrefabInstance(tile);
            });
        }

        [Test]
        public void BoundaryWalls_WrapTheZoneAndLeaveThePortalGapOpen()
        {
            InScene(ZoneSceneBaker.SafeZonePath, scene =>
            {
                Transform walls = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.BoundaryWallsName);
                Assert.IsNotNull(walls);

                int segments = Mathf.RoundToInt(ZoneSceneBaker.GroundExtent / ZoneSceneBaker.GroundTile);
                Assert.AreEqual(segments * 4 - 2, walls.childCount,
                    "Four full edges minus the two segments that make the portal gap.");

                foreach (Transform wall in walls)
                {
                    AssertIsGrayboxPrefabInstance(wall);

                    Vector3 p = wall.localPosition;
                    bool onExitEdge = Mathf.Abs(p.z - ZoneSceneBaker.GroundExtent / 2f) < 0.01f;
                    bool inGap = Mathf.Abs(Mathf.Abs(p.x) - ZoneSceneBaker.GroundTile / 2f) < 0.01f;
                    Assert.IsFalse(onExitEdge && inGap, "The portal gap must stay clear of walls.");
                }
            });
        }

        [Test]
        public void SafeZone_HasKitBuildings()
        {
            InScene(ZoneSceneBaker.SafeZonePath, scene =>
            {
                Transform buildings = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.BuildingsName);
                Assert.IsNotNull(buildings);
                Assert.Greater(buildings.childCount, 0);

                foreach (Transform building in buildings)
                {
                    Assert.Greater(building.childCount, 0, $"'{building.name}' should be assembled from kit pieces.");
                    foreach (Transform piece in building)
                        AssertIsGrayboxPrefabInstance(piece);
                }
            });
        }

        [Test]
        public void Wilderness_IsScatteredWithKitPieces()
        {
            InScene(ZoneSceneBaker.WildernessZonePath, scene =>
            {
                Transform scatter = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.ScatterName);
                Assert.IsNotNull(scatter);
                Assert.Greater(scatter.childCount, 0, "A wilderness needs landmarks to navigate by.");

                foreach (Transform piece in scatter)
                    AssertIsGrayboxPrefabInstance(piece);
            });
        }

        // ---- Spawn points --------------------------------------------------

        [Test]
        public void SpawnPoints_AreWiredIntoThePlayerSpawner()
        {
            InScene(ZoneSceneBaker.SafeZonePath, scene =>
            {
                Transform spawnPoints = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.SpawnPointsName);
                Assert.IsNotNull(spawnPoints);
                Assert.AreEqual(ZoneSceneBaker.SpawnPointCount, spawnPoints.childCount);

                Assert.IsTrue(NetworkManagerSceneBaker.TryFind(scene, out NetworkManager manager));
                var spawner = manager.GetComponent<PlayerSpawner>();
                Assert.IsNotNull(spawner);
                Assert.AreEqual(ZoneSceneBaker.SpawnPointCount, spawner.Spawns.Length);

                foreach (Transform spawn in spawner.Spawns)
                {
                    Assert.IsNotNull(spawn);
                    Assert.IsTrue(spawn.IsChildOf(spawnPoints),
                        "Only this zone's own spawn points, never a leftover from another scene.");
                }
            });
        }

        // ---- Idempotency ---------------------------------------------------

        [Test]
        public void ZoneBaker_IsIdempotent()
        {
            string[] first = Describe(ZoneSceneBaker.SafeZonePath);

            ZoneSceneBaker.BuildSafeZone();

            // Building leaves the freshly saved scene active; unload it so Describe re-opens the
            // file from disk rather than handing back the live copy.
            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

            string[] second = Describe(ZoneSceneBaker.SafeZonePath);

            CollectionAssert.AreEqual(first, second,
                "A second build must regenerate the identical scene, not stack another on top of it.");
            Assert.AreEqual(1, second.Count(line => line.StartsWith("NetworkManager#", StringComparison.Ordinal)),
                "Exactly one NetworkManager, however many times the baker runs.");
        }

        // ---- Helpers -------------------------------------------------------

        private static void InScene(string path, Action<Scene> assert)
        {
            Scene scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Additive);
            try
            {
                assert(scene);
            }
            finally
            {
                EditorSceneManager.CloseScene(scene, true);
            }
        }

        private static T FromScene<T>(string path, Func<Scene, T> read)
        {
            Scene scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Additive);
            try
            {
                return read(scene);
            }
            finally
            {
                EditorSceneManager.CloseScene(scene, true);
            }
        }

        private static GameObject FindRoot(Scene scene, string name)
        {
            foreach (GameObject root in scene.GetRootGameObjects())
            {
                if (root.name == name)
                    return root;
            }

            Assert.Fail($"Scene '{scene.name}' has no root object named '{name}'.");
            return null;
        }

        private static Transform ChildOf(GameObject root, string name)
            => root.transform.Find(name);

        private static ushort PortOf(string path) => FromScene(path, scene =>
        {
            Assert.IsTrue(NetworkManagerSceneBaker.TryFind(scene, out NetworkManager manager));
            return manager.GetComponent<Tugboat>().GetPort();
        });

        private static string ZoneIdOf(string path) => FromScene(path, scene =>
        {
            Assert.IsTrue(NetworkManagerSceneBaker.TryFind(scene, out NetworkManager manager));
            return manager.GetComponent<SocialHubService>().ZoneId;
        });

        private static bool UseTokenAuthOf(string path) => FromScene(path, scene =>
        {
            Assert.IsTrue(NetworkManagerSceneBaker.TryFind(scene, out NetworkManager manager));
            return manager.GetComponent<MMOConnectionGate>().Settings.UseTokenAuth;
        });

        private static ZoneRiskTier RiskTierOf(string path) => FromScene(path, scene =>
        {
            Transform config = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), ZoneSceneBaker.RiskConfigName);
            Assert.IsNotNull(config, "Every zone declares its risk tier.");
            return config.GetComponent<ZoneRiskConfig>().Tier;
        });

        private static PortalFields PortalOf(string path, string portalName) => FromScene(path, scene =>
        {
            Transform portal = ChildOf(FindRoot(scene, ZoneSceneBaker.ZoneRootName), portalName);
            Assert.IsNotNull(portal, $"Expected '{portalName}' road out of the zone.");

            var trigger = portal.GetComponent<ZoneTransferTrigger>();
            Assert.IsNotNull(trigger);

            var serialized = new SerializedObject(trigger);
            return new PortalFields(
                serialized.FindProperty("_targetHost").stringValue,
                (ushort)serialized.FindProperty("_targetPort").intValue,
                serialized.FindProperty("_targetServerId").stringValue,
                serialized.FindProperty("_targetZoneName").stringValue,
                serialized.FindProperty("_sourceServerId").stringValue);
        });

        private static void AssertIsGrayboxPrefabInstance(Transform piece)
        {
            Assert.IsTrue(PrefabUtility.IsPartOfPrefabInstance(piece.gameObject),
                $"'{piece.name}' is a loose object, not an instance of a kit prefab.");

            string assetPath = PrefabUtility.GetPrefabAssetPathOfNearestInstanceRoot(piece.gameObject);
            StringAssert.StartsWith("Assets/Prefabs/Graybox/", assetPath,
                "Every zone piece must come from the primitive prefab kit (no ProBuilder meshes).");
        }

        private static string[] Describe(string path)
        {
            Scene scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Additive);
            try
            {
                var lines = new List<string>();
                foreach (GameObject root in scene.GetRootGameObjects())
                    lines.Add($"{root.name}#{root.transform.childCount}");

                lines.Sort(StringComparer.Ordinal);
                return lines.ToArray();
            }
            finally
            {
                EditorSceneManager.CloseScene(scene, true);
            }
        }

        private readonly struct PortalFields
        {
            public readonly string TargetHost;
            public readonly ushort TargetPort;
            public readonly string TargetServerId;
            public readonly string TargetZoneName;
            public readonly string SourceServerId;

            public PortalFields(string targetHost, ushort targetPort, string targetServerId, string targetZoneName, string sourceServerId)
            {
                TargetHost = targetHost;
                TargetPort = targetPort;
                TargetServerId = targetServerId;
                TargetZoneName = targetZoneName;
                SourceServerId = sourceServerId;
            }
        }
    }
