namespace MMO.Gameplay
{
    /// <summary>
    /// Pure threat arithmetic: how much threat an ability generates, when the table should
    /// switch targets, and the taunt floor that forces a tank to the top.
    /// </summary>
    public static class ThreatRules
    {
        /// <summary>
        /// Threat added when a tank uses a taunt ability. This value is intentionally high
        /// enough to exceed any accumulated threat from damage or healing, ensuring the tank
        /// immediately becomes the target.
        /// </summary>
        public const float TauntFloor = 10000f;

        /// <summary>
        /// Healing generates threat at this fraction of the amount healed. Standard MMO value is 0.5.
        /// </summary>
        public const float HealingThreatRatio = 0.5f;

        /// <summary>
        /// A new challenger must exceed the incumbent's threat by this margin to become the target.
        /// A value of 0.1f means the challenger needs 110% of the incumbent's threat.
        /// </summary>
        public const float SwitchMargin = 0.1f;

        /// <summary>
        /// Computes the threat generated by an ability cast.
        /// </summary>
        /// <param name="logic">The ability's logic type.</param>
        /// <param name="amount">The raw amount (damage dealt or healing done).</param>
        /// <returns>The threat value to add to the threat table.</returns>
        public static float ThreatFor(AbilityLogic logic, int amount)
        {
            return logic switch
            {
                AbilityLogic.Taunt => TauntFloor,
                AbilityLogic.TargetedDamage => amount,
                AbilityLogic.AreaDamage => amount,
                AbilityLogic.Heal => amount * HealingThreatRatio,
                AbilityLogic.SelfHeal => 0f,
                _ => 0f,
            };
        }

        /// <summary>
        /// Determines whether the threat table should switch from the current target
        /// to a new challenger. The challenger must exceed the incumbent by the switch margin.
        /// </summary>
        /// <param name="incumbentThreat">Current target's threat.</param>
        /// <param name="challengerThreat">New challenger's threat.</param>
        /// <returns>True if the target should switch.</returns>
        public static bool ShouldSwitch(float incumbentThreat, float challengerThreat)
        {
            if (incumbentThreat <= 0f)
                return true;

            return challengerThreat >= incumbentThreat * (1f + SwitchMargin);
        }
    }
}